package io.github.arcangelotanzi.assistant;

import io.github.arcangelotanzi.assistant.customer.Customer;
import io.github.arcangelotanzi.assistant.customer.CustomerRepository;
import io.github.arcangelotanzi.assistant.order.Order;
import io.github.arcangelotanzi.assistant.order.OrderRepository;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.boot.test.context.TestConfiguration;
import org.springframework.boot.webmvc.test.autoconfigure.AutoConfigureMockMvc;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Import;
import org.springframework.context.annotation.Primary;
import org.springframework.http.HttpStatus;
import org.springframework.http.MediaType;
import org.springframework.test.web.servlet.assertj.MockMvcTester;
import org.springframework.test.web.servlet.assertj.MvcTestResult;

import java.math.BigDecimal;
import java.time.Clock;
import java.time.Instant;
import java.time.LocalDate;
import java.time.ZoneId;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * End-to-end tests: real HTTP layer, services, transactions and PostgreSQL, no mocks.
 * Only the clock is replaced, so "today" is always 2026-10-21 in Europe/Rome.
 */
@SpringBootTest
@AutoConfigureMockMvc
@Import({TestcontainersConfiguration.class, ApiIntegrationTest.FixedClockConfig.class})
class ApiIntegrationTest {

    @TestConfiguration
    static class FixedClockConfig {

        @Bean
        @Primary
        Clock fixedClock() {
            return Clock.fixed(Instant.parse("2026-10-21T10:00:00Z"), ZoneId.of("Europe/Rome"));
        }
    }

    @Autowired
    private MockMvcTester mvc;

    @Autowired
    private CustomerRepository customerRepository;

    @Autowired
    private OrderRepository orderRepository;

    @AfterEach
    void cleanUp() {
        // No rollback with @SpringBootTest: delete what each test committed, orders first (foreign key)
        orderRepository.deleteAll();
        customerRepository.deleteAll();
    }

    @Test
    void createdCustomerCanBeReadBackFromTheLocationHeader() {
        MvcTestResult created = createCustomer("Rossi S.r.l.", "rossi@test.example");
        assertThat(created).hasStatus(HttpStatus.CREATED);
        String location = created.getResponse().getHeader("Location");

        assertThat(mvc.get().uri(location))
                .hasStatusOk()
                .bodyJson()
                .isLenientlyEqualTo("""
                        {"name":"Rossi S.r.l.","email":"rossi@test.example"}
                        """);

        // createdAt is generated by PostgreSQL and must survive the whole trip back to JSON
        assertThat(mvc.get().uri(location))
                .bodyJson()
                .extractingPath("$.createdAt").isNotNull();
    }

    @Test
    void secondCustomerWithTheSameEmailIsRejectedWithConflict() {
        assertThat(createCustomer("Rossi S.r.l.", "rossi@test.example")).hasStatus(HttpStatus.CREATED);

        assertThat(createCustomer("Altro nome", "rossi@test.example"))
                .hasStatus(HttpStatus.CONFLICT)
                .hasContentType(MediaType.APPLICATION_PROBLEM_JSON);

        assertThat(customerRepository.count()).isEqualTo(1);
    }

    @Test
    void lateOrdersAnswerWhichCustomersToContact() {
        // Arranged through repositories: the API itself refuses delivery dates in the past
        Customer customer = customerRepository.save(
                new Customer("Rossi S.r.l.", "rossi@test.example", "+39 02 1234567"));
        orderRepository.save(new Order(customer,
                LocalDate.of(2026, 10, 10), LocalDate.of(2026, 10, 18), new BigDecimal("1250.00")));
        orderRepository.save(new Order(customer,
                LocalDate.of(2026, 10, 10), LocalDate.of(2026, 10, 25), new BigDecimal("80.00")));

        assertThat(mvc.get().uri("/api/orders/late"))
                .hasStatusOk()
                .bodyJson()
                .isLenientlyEqualTo("""
                        [{"customerName":"Rossi S.r.l.","customerEmail":"rossi@test.example",
                          "promisedDeliveryDate":"2026-10-18","daysLate":3,"totalAmount":1250.00}]
                        """);
    }

    @Test
    void orderPromisedInThePastIsRejectedAndNotSaved() {
        Customer customer = customerRepository.save(new Customer("Rossi S.r.l.", "rossi@test.example", null));

        assertThat(mvc.post().uri("/api/orders")
                .contentType(MediaType.APPLICATION_JSON)
                .content("""
                        {"customerId":%d,"promisedDeliveryDate":"2026-10-20","totalAmount":100.00}
                        """.formatted(customer.getId())))
                .hasStatus(HttpStatus.UNPROCESSABLE_CONTENT);

        assertThat(orderRepository.count()).isZero();
    }

    @Test
    void openApiDocumentDescribesTheEndpoints() {
        assertThat(mvc.get().uri("/v3/api-docs"))
                .hasStatusOk()
                .bodyJson()
                // Bracket notation because the key contains slashes
                .extractingPath("$.paths['/api/orders/late']").isNotNull();
    }

    private MvcTestResult createCustomer(String name, String email) {
        return mvc.post().uri("/api/customers")
                .contentType(MediaType.APPLICATION_JSON)
                .content("""
                        {"name":"%s","email":"%s"}
                        """.formatted(name, email))
                .exchange();
    }
}
